export const dictionaries: Record<Lang, Dict> = { en, ar, fr };

function resolve(dict: Dict, path: string): string {
  const parts = path.split(".");
  let node: string | Dict = dict;
  for (const part of parts) {
    if (typeof node === "string") return path;
    node = node[part];
    if (node === undefined) return path;
  }
  return typeof node === "string" ? node : path;
}

const LANG_ORDER: Lang[] = ["en", "ar", "fr"];

type LanguageContextValue = {
  lang: Lang;
  /** Cycles en → ar → fr → en. Kept for any existing callers. */
  toggleLang: () => void;
  /** Sets the language directly — used by the 3-way selector in Nav. */
  setLang: (lang: Lang) => void;
  t: (path: string) => string;
};

const LanguageContext = createContext<LanguageContextValue | null>(null);

const STORAGE_KEY = "atlas-trading.lang";

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  // Always start at "en" so the server-rendered HTML and the client's first
  // render match exactly — reading localStorage here would return a
  // different value than the server used, causing a hydration mismatch.
  const [lang, setLang] = useState<Lang>("en");

  useEffect(() => {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    // Restoring a persisted preference after mount (client-only) avoids the
    // SSR/client mismatch described above.
    // eslint-disable-next-line react-hooks/set-state-in-effect
    if (stored === "ar" || stored === "en" || stored === "fr") setLang(stored);
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
    window.localStorage.setItem(STORAGE_KEY, lang);
  }, [lang]);

  const toggleLang = () => setLang((l) => LANG_ORDER[(LANG_ORDER.indexOf(l) + 1) % LANG_ORDER.length]);
  const t = (path: string) => resolve(dictionaries[lang], path);

  return (
    <LanguageContext.Provider value={{ lang, toggleLang, setLang, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error("useLanguage must be used within LanguageProvider");
  return ctx;
}


/** Renders its children in a fixed language, independent of the site's language (used by the Social Media Studio canvas). */
export function LanguageOverride({ lang, children }: { lang: Lang; children: React.ReactNode }) {
  const parent = useLanguage();
  const t = (path: string) => resolve(dictionaries[lang], path);
  return <LanguageContext.Provider value={{ ...parent, lang, t }}>{children}</LanguageContext.Provider>;
}
